'use strict';
// Hook wiring of the guardrails for coding agents other than Claude Code: which file to write, at which
// scope, and in which format. Used by setup.cjs (project scope, path relative to the project root) and
// by the ultime-skill installer (user scope, absolute path). Every entry it writes contains MARK, which
// is how it finds and replaces its own entries without touching anything else in a shared settings file.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const MARK = 'hooks/guardrails/guard.cjs';
const USER_MARK = 'guardrails/runtime/guard.cjs';

/**
 * Where each harness reads hooks. `project` is relative to the project root, `user` to the home
 * directory; a missing scope means the harness has no hook file there (or none documented).
 */
const TARGETS = {
  codex: { project: '.codex/hooks.json', user: '.codex/hooks.json', format: 'claude', event: 'PreToolUse', matcher: 'Bash|apply_patch|Edit|Write' },
  gemini: { project: '.gemini/settings.json', user: '.gemini/settings.json', format: 'claude', event: 'BeforeTool', matcher: 'run_shell_command|write_file|replace', timeout: 10000 },
  qwen: { project: '.qwen/settings.json', user: '.qwen/settings.json', format: 'claude', event: 'PreToolUse', matcher: 'run_shell_command|write_file|edit|Bash|Write|Edit' },
  droid: { project: '.factory/settings.json', user: '.factory/settings.json', format: 'claude', event: 'PreToolUse', matcher: 'Execute|Edit|Create|ApplyPatch' },
  cursor: { project: '.cursor/hooks.json', user: '.cursor/hooks.json', format: 'cursor' },
  copilot: { project: '.github/hooks/guardrails.json', user: '.copilot/hooks/guardrails.json', format: 'copilot' },
  kiro: { project: '.kiro/hooks/guardrails.json', format: 'kiro' },
  opencode: { project: '.opencode/plugins/guardrails.js', user: '.config/opencode/plugins/guardrails.js', format: 'js' },
  kilo: { project: '.kilo/plugins/guardrails.js', format: 'js' },
};

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return {};
    throw new Error(`${file} is not valid JSON (${error.message}): fix it first`);
  }
}

function writeFile(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

/** Write a settings object back, or delete the file when removing our entries left it empty. */
function writeSettings(file, settings, remove) {
  const rest = Object.keys(settings).filter((key) => key !== 'version');
  if (remove && !rest.length) fs.rmSync(file, { force: true });
  else writeFile(file, `${JSON.stringify(settings, null, 2)}
`);
}

const ours = (command) => typeof command === 'string' && (command.includes(MARK) || command.includes(USER_MARK));

/** Remove our groups from a Claude-shaped `hooks` object (Codex, Gemini, Qwen, Droid). */
function withoutClaudeShaped(settings) {
  const hooks = settings.hooks || {};
  for (const event of Object.keys(hooks)) {
    if (!Array.isArray(hooks[event])) continue;
    hooks[event] = hooks[event]
      .map((group) => ({ ...group, hooks: (group.hooks || []).filter((hook) => !ours(hook.command)) }))
      .filter((group) => group.hooks.length);
    if (!hooks[event].length) delete hooks[event];
  }
  if (Object.keys(hooks).length) settings.hooks = hooks;
  else delete settings.hooks;
  return settings;
}

/** Remove our entries from a flat `hooks: {event: [entry]}` object (Cursor). */
function withoutFlat(settings) {
  const hooks = settings.hooks || {};
  for (const event of Object.keys(hooks)) {
    if (!Array.isArray(hooks[event])) continue;
    hooks[event] = hooks[event].filter((entry) => !ours(entry.command));
    if (!hooks[event].length) delete hooks[event];
  }
  if (Object.keys(hooks).length) settings.hooks = hooks;
  else delete settings.hooks;
  return settings;
}

/** Source of the OpenCode/Kilo plugin that runs the guard before each tool call. */
function jsShim(guard, harness) {
  return [
    '// Generated by the ultime-skill guardrails: runs the guardrails hook before each tool call and',
    '// blocks the call when it denies. Remove this file (or run setup.cjs uninstall-project) to disable.',
    "import { spawnSync } from 'node:child_process';",
    "import path from 'node:path';",
    '',
    'export const Guardrails = async ({ directory, worktree }) => ({',
    "  'tool.execute.before': async (input, output) => {",
    `    const guard = ${guard.relative ? `path.join(worktree || directory, ${JSON.stringify(guard.path)})` : JSON.stringify(guard.path)};`,
    "    const payload = { hook_event_name: 'PreToolUse', cwd: directory, tool_name: input.tool, tool_input: output.args };",
    `    const result = spawnSync('node', [guard, '--harness', ${JSON.stringify(harness)}], { input: JSON.stringify(payload), encoding: 'utf8' });`,
    "    if (result.status === 2) throw new Error((result.stderr || 'Blocked by the guardrails').trim());",
    '  },',
    '});',
    '',
  ].join('\n');
}

/**
 * Write (or with remove=true, take out) the guardrails hook of one harness.
 *
 * @param {string} harness Harness id (a key of TARGETS).
 * @param {'project' | 'user'} scope Scope.
 * @param {string} base Project root for the project scope, home directory for the user scope.
 * @param {{path: string, relative: boolean}} guard Guard script: relative to the project root, or absolute.
 * @param {boolean} [remove] Remove instead of install.
 * @returns {string | null} File written, or null when the harness has no hook file at that scope.
 */
function wire(harness, scope, base, guard, remove = false) {
  const target = TARGETS[harness];
  if (!target || !target[scope]) return null;
  const file = path.join(base, target[scope]);
  const command = `node ${JSON.stringify(guard.path.replace(/\\/g, '/'))} --harness ${harness}`;
  if (target.format === 'js' || target.format === 'kiro' || target.format === 'copilot') {
    // Files that hold only our hook: write or delete them whole.
    if (remove) {
      fs.rmSync(file, { force: true });
      return file;
    }
    if (target.format === 'js') writeFile(file, jsShim(guard, harness));
    if (target.format === 'kiro') {
      writeFile(file, `${JSON.stringify({ version: 'v1', hooks: [{ name: 'guardrails', trigger: 'PreToolUse', matcher: '*', action: { type: 'command', command } }] }, null, 2)}\n`);
    }
    if (target.format === 'copilot') {
      const entry = { type: 'command', bash: command, powershell: command, timeoutSec: 10 };
      writeFile(file, `${JSON.stringify({ version: 1, hooks: { preToolUse: [entry] } }, null, 2)}\n`);
    }
    return file;
  }
  if (target.format === 'cursor') {
    const settings = withoutFlat(readJson(file));
    if (!remove) {
      settings.version = settings.version || 1;
      settings.hooks = settings.hooks || {};
      settings.hooks.preToolUse = [...(settings.hooks.preToolUse || []), { command }];
    }
    writeSettings(file, settings, remove);
    return file;
  }
  const settings = withoutClaudeShaped(readJson(file));
  if (!remove) {
    settings.hooks = settings.hooks || {};
    const hook = { type: 'command', command, timeout: target.timeout || 10 };
    settings.hooks[target.event] = [...(settings.hooks[target.event] || []), { matcher: target.matcher, hooks: [hook] }];
  }
  writeSettings(file, settings, remove);
  return file;
}

/** Home directory, overridable for tests. */
function home() {
  return process.env.ULTIME_SKILL_HOME || os.homedir();
}

module.exports = { TARGETS, MARK, wire, home };
